import assert from 'node:assert/strict';
import {spawn} from 'node:child_process';
import {mkdtemp,rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join,resolve,sep} from 'node:path';
import {fileURLToPath} from 'node:url';
import net from 'node:net';

const root=fileURLToPath(new URL('../',import.meta.url));
const temporary=await mkdtemp(join(tmpdir(),'qa-review-test-'));
const probe=net.createServer();await new Promise(r=>probe.listen(0,'127.0.0.1',r));
const port=probe.address().port;await new Promise(r=>probe.close(r));
const origin='http://127.0.0.1:'+port;
const child=spawn(process.execPath,['dist/server/index.mjs'],{cwd:root,env:{...process.env,PORT:String(port),QA_DATA_DIR:temporary,OPENAI_API_KEY:''},stdio:['ignore','pipe','pipe'],windowsHide:true});
let logs='';child.stdout.on('data',b=>{logs+=b;});child.stderr.on('data',b=>{logs+=b;});
try{
 await new Promise((ready,reject)=>{const timeout=setTimeout(()=>{clearInterval(poll);reject(new Error('Server startup timeout: '+logs));},10000);const poll=setInterval(()=>{if(logs.includes('QA Avatar Command is running.')){clearInterval(poll);clearTimeout(timeout);ready();}},50);});
 const call=async(path,body,method='POST')=>{const response=await fetch(origin+path,{method,headers:{Origin:origin,'Content-Type':'application/json'},body:body===undefined?undefined:JSON.stringify(body)});return {status:response.status,data:await response.json()};};
 let workspace=await call('/api/workspace',undefined,'GET');assert.equal(workspace.status,200);
 const state=workspace.data.state;
 const project={id:'review-api-project',name:'Review API Test',avatarId:'',environment:'',build:'',requirements:'The system must require numeric NID input with a maximum length of 17 digits.\nThe system must display the employee profile quickly.',cases:[],bugs:[]};
 state.projects=[project];
 let saved=await call('/api/workspace',{state,revision:workspace.data.revision},'PUT');assert.equal(saved.status,200);
 const analyze=()=>call('/api/documents/analyze',{projectId:project.id,id:'pasted'});
 const first=await analyze();assert.equal(first.status,200);assert.deepEqual(first.data.analysis.cases,[]);assert.equal(first.data.analysis.requirements.length,2);
 assert.equal((await call('/api/documents/analyze',{projectId:project.id,action:'generate'})).status,409);
 const review={documentId:'pasted',documentName:'Pasted Requirements',mode:'rules',summary:first.data.analysis.summary,gaps:first.data.analysis.gaps,gapDetails:first.data.analysis.gapDetails,processReview:first.data.analysis.processReview,requirements:first.data.analysis.requirements.map((r,index)=>({...r,included:index===0})),finalized:false};
 project.requirementReview=review;
 saved=await call('/api/workspace',{state,revision:saved.data.revision},'PUT');assert.equal(saved.status,200);
 assert.equal((await call('/api/documents/analyze',{projectId:project.id,action:'generate'})).status,409);
 review.finalized=true;
 saved=await call('/api/workspace',{state,revision:saved.data.revision},'PUT');assert.equal(saved.status,200);
 const generated=await call('/api/documents/analyze',{projectId:project.id,action:'generate',requirements:[{id:'injected',statement:'Invented requirement'}]});
 assert.equal(generated.status,200);
 assert.ok(generated.data.cases.every(c=>c.requirementIds.length===1&&c.requirementIds[0]==='Line 1'));
 assert.ok(generated.data.cases.every(c=>c.preconditions&&c.testData&&c.steps&&c.expected));
 workspace=await call('/api/workspace',undefined,'GET');assert.equal(workspace.data.state.projects[0].cases.length,0);
 assert.equal(workspace.data.state.projects[0].requirementReview.finalized,true);
 assert.equal(workspace.data.state.projects[0].requirementReview.processReview.areas.length,14);
 assert.equal(new Set(workspace.data.state.projects[0].requirementReview.processReview.scenarios.flatMap(s=>s.requirementIds)).size,2);
 assert.equal(workspace.data.state.projects[0].requirementReview.gapDetails[0].originalText,'The system must display the employee profile quickly.');
 assert.ok(workspace.data.state.projects[0].requirementReview.gapDetails[0].question.includes('How quickly'));
 project.cases=generated.data.cases;
 saved=await call('/api/workspace',{state,revision:saved.data.revision},'PUT');assert.equal(saved.status,200);
 workspace=await call('/api/workspace',undefined,'GET');assert.equal(workspace.data.state.projects[0].cases.length,generated.data.cases.length);
 review.finalized=false;
 saved=await call('/api/workspace',{state,revision:saved.data.revision},'PUT');assert.equal(saved.status,200);
 assert.equal((await call('/api/documents/analyze',{projectId:project.id,action:'generate'})).status,409);
 delete project.requirementReview;
 saved=await call('/api/workspace',{state,revision:saved.data.revision},'PUT');assert.equal(saved.status,200);
 workspace=await call('/api/workspace',undefined,'GET');
 assert.equal(workspace.data.state.projects[0].requirementReview,undefined);
 assert.equal(workspace.data.state.projects[0].cases.length,generated.data.cases.length);
 assert.ok(workspace.data.state.projects[0].requirements.includes('numeric NID'));
 assert.equal((await analyze()).status,200);
 console.log('Review API checks passed: analysis without cases, persisted checklist, finalization gate, selected-only generation, ignored injected requirements and explicit case save.');
}finally{
 const closed=new Promise(r=>child.once('exit',r));child.kill();await closed;
 const resolved=resolve(temporary),parent=resolve(tmpdir());
 if(!resolved.startsWith(parent+sep)||!resolved.split(sep).at(-1).startsWith('qa-review-test-'))throw new Error('Unexpected temporary cleanup path');
 await rm(resolved,{recursive:true,force:true});
}
